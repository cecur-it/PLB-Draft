#!/usr/bin/env python3
"""Emit a Compose override that puts every service on ONE network (keeping each service's aliases).

Why: a few Docker daemons (observed: Engine 29.1.3 on a Codespaces host) answer embedded-DNS queries with the target
container's address on a network the *caller is not attached to*. With the stack's six segmented networks that makes
multi-homed services (fluentd, sink, opensearch, ...) unreachable from their peers although every service is healthy.
tests/smoke-test.sh runs a probe for exactly this and, only when the probe fails, layers this override on top so the
pipeline logic can still be verified. Production (Helm/NetworkPolicies) and normal Compose runs keep the segmentation.

Usage: docker compose <same -f/--profile flags> config --format json | python3 tests/flatten-networks.py > override.yml
"""
import json
import sys


def main() -> int:
    cfg = json.load(sys.stdin)
    out = ["# generated by tests/flatten-networks.py — every service on one network (see that script for why)", "services:"]
    for name, svc in sorted(cfg.get("services", {}).items()):
        nets = svc.get("networks")
        if not nets:
            continue
        aliases = sorted({a for n in nets.values() for a in ((n or {}).get("aliases") or [])})
        out.append(f"  {name}:")
        out.append("    networks: !override")
        out.append("      flat:" + (f" {{aliases: {json.dumps(aliases)}}}" if aliases else " {}"))
    out += ["networks:", "  flat:", "    name: vendetta-stack_flat", "    driver: bridge"]
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
